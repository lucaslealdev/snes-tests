#!/usr/bin/env python3
"""Generates the ld65 configuration (LoROM, 1MB, no SRAM) from the bank counts of the test generators.

Usage: gen_cfg.py cpu-meta.json spc-meta.json > snes-tests.cfg

Bank layout:
  0                     harness code, RODATA, TEST_DATA ($00FFA0, used by the tests), header, vectors
  1 .. B                CPU tests (CPUBANK1..CPUBANKB)
  next                  GFX, STRINGS, META_CPU, META_B (one bank each)
  next S banks          SPC test programs (SPC0..SPC<S-1>)
The WRAM area reserved for the runner state (RSVSTATE) is $7FA000-$7FDFFF. tools/audit_wram.py proves that
no test touches it.
"""
import json
import sys

ROM_BANKS = 32  # 1MB


def main():
    cpu = json.load(open(sys.argv[1]))
    spc = json.load(open(sys.argv[2]))
    banks = ['ROM']
    segs = {}  # segment name -> bank area
    names = [('CPUBANK%d' % i) for i in range(1, cpu['banks'] + 1)]
    names += ['GFX', 'STRINGS', 'META_CPU', 'META_B']
    names += [('SPC%d' % i) for i in range(spc['files'])]
    if 1 + len(names) > ROM_BANKS:
        sys.exit(f'Too many banks: {1 + len(names)} > {ROM_BANKS}')
    out = ['# Auto-generated by tools/gen_cfg.py. Do not edit.', '', 'MEMORY {',
           '    ZEROPAGE:   start =      0, size =  $100;',
           '    BSS:        start =   $200, size = $1800;',
           '    RSVWRAM:    start = $7FA000, size = $4000;  # runner state, see tools/audit_wram.py',
           '    ROM:        start =  $8000, size = $8000, fill = yes;']
    for i in range(1, ROM_BANKS):
        out.append(f'    BANK{i}:'.ljust(16) + f'start = ${i:02X}8000, size = $8000, fill = yes;')
    out += ['}', '', 'SEGMENTS {',
            '    ZEROPAGE:   load = ZEROPAGE,    type = zp;',
            '    BSS:        load = BSS,         type = bss, align = $100, optional = yes;',
            '    RSVSTATE:   load = RSVWRAM,     type = bss;',
            '    CODE:       load = ROM,         align = $8000;',
            '    RODATA:     load = ROM;',
            '    TEST_DATA:  load = ROM,         start =  $FFA0;',
            '    HEADER:     load = ROM,         start =  $FFC0;',
            '    ROMINFO:    load = ROM,         start =  $FFD5, optional = yes;',
            '    VECTORS:    load = ROM,         start =  $FFE0;', '']
    for i, name in enumerate(names, start=1):
        out.append(f'    {name}:'.ljust(16) + f'load = BANK{i},'.ljust(20) + 'optional = yes;')
    out += ['}', '']
    sys.stdout.write('\n'.join(out))


main()
